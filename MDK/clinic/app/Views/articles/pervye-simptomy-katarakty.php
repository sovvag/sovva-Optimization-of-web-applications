<p class="lead">С возрастом многие замечают, что зрение стало хуже. Картинка теряет чёткость, цвета кажутся блеклыми, а вечером читать становится сложнее. Часто эти изменения списывают на усталость или возраст. На самом деле так могут проявляться первые симптомы катаракты.</p>
<p>Катаракта – это помутнение природного хрусталика глаза. Хрусталик работает как линза. Когда он мутнеет, свет проходит хуже, и зрение снижается. Заболевание развивается постепенно, поэтому важно вовремя заметить признаки и обратиться к врачу.</p>

<h2>Что такое катаракта</h2>
<p>Хрусталик расположен внутри глаза и отвечает за фокусировку изображения. В молодости он прозрачный и эластичный. С годами его структура меняется, появляется помутнение. Чаще всего катаракта развивается после 50–60 лет. Иногда она может появиться раньше из-за травм, сахарного диабета или длительного приёма некоторых лекарств.</p>
<p>Катаракта не вызывает боли и покраснения глаз. Поэтому человек долго может не обращать внимания на изменения.</p>

