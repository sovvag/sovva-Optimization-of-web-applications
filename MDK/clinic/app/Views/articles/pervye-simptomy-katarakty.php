<h3>Затуманенное и размытое зрение</h3>
<p>Мир кажется будто через запотевшее стекло. Мелкий шрифт читать труднее.</p>
<h3>Ореолы и «засвет» вокруг источников света</h3>
<p>Вокруг фонарей и фар появляются светящиеся круги. Особенно это заметно вечером и ночью.</p>
<h3>Ухудшение зрения в сумерках и ночью</h3>
<p>Днём человек ещё видит относительно нормально, а в тёмное время суток зрение заметно падает.</p>
<h3>Изменение восприятия цветов</h3>
<p>Краски становятся тусклыми, всё приобретает желтоватый оттенок.</p>
<h3>Двоение в одном глазу</h3>
<p>Даже если закрыть второй глаз, изображение может двоиться.</p>
<h3>Частая смена очков</h3>
<p>Очки, которые раньше подходили, перестают помогать. Приходится чаще менять рецепт.</p>
